#!/usr/bin/env python3
"""Generate Ctx + non-Ctx wrappers for the npps constant arithmetic families
(api_analysis/packages/p1.1b.csv).  Every `_Ctx` entry dispatches to a single
npps::constant executor; the plain entry forwards to it via nppGetStreamContext().

Usage: python3 mpp_scripts/gen_constant_wrappers.py [--emit]
"""
import csv, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV = ROOT / "api_analysis" / "packages" / "p1.1b.csv"
OUT = ROOT / "src" / "npps" / "npps_arithmetic_operations" / "npps_constant_generated.cpp"

CTY = {"8u":"Npp8u","8s":"Npp8s","16u":"Npp16u","16s":"Npp16s","16sc":"Npp16sc",
       "32u":"Npp32u","32s":"Npp32s","32sc":"Npp32sc","32f":"Npp32f","32fc":"Npp32fc",
       "64f":"Npp64f","64fc":"Npp64fc","64s":"Npp64s","64u":"Npp64u"}

SAME_TYPE_OP = {
    "nppsAddC":"addC","nppsSubC":"subC","nppsSubCRev":"subCRev","nppsMulC":"mulC",
    "nppsDivC":"divC","nppsDivCRev":"divCRev","nppsAndC":"andC","nppsOrC":"orC","nppsXorC":"xorC",
}

def param_names(params):
    names = []
    for x in params.split(","):
        name = x.replace("*", " ").split()[-1]
        names.append(name)
    return names

def executor_call(row):
    base = row["function_name"].replace("_Ctx", "")
    p = row["params"]
    scale = "nScaleFactor" in p
    inplace = "pSrcDst" in p
    bits = row["family"] in ("nppsAndC", "nppsOrC", "nppsXorC")
    if row["family"] == "nppsNormalize":
        dt = row["dtype"]
        A = CTY[dt]
        DV = {"32fc":"Npp32f","64fc":"Npp64f","16s":"int","16sc":"int"}.get(dt, A)
        sf = "nScaleFactor" if "nScaleFactor" in row["params"] else "0"
        return (f"npps::constant::normalize<{A}, {DV}>(pSrc, vSub, vDiv, pDst, nLength, "
                f"{sf}, nppStreamCtx.hStream)")
    if base.startswith("nppsMulC_32f16s_Sfs"):
        return "npps::constant::mulCFloatToI16(pSrc, nValue, pDst, nLength, nScaleFactor, nppStreamCtx.hStream)"
    if base.startswith("nppsMulC_64f64s_I"):
        return "npps::constant::mulCInplaceFloatToI64(nValue, pDst, nLength, nScaleFactor, nppStreamCtx.hStream)"
    if base.startswith("nppsMulC_Low"):
        return "npps::constant::mulCLow(pSrc, nValue, pDst, nLength, nppStreamCtx.hStream)"
    if row["family"] == "nppsAddProductC":
        return "npps::constant::addProductC(pSrc, nValue, pDst, nLength, nppStreamCtx.hStream)"
    op = SAME_TYPE_OP[row["family"]]
    A = CTY[row["dtype"]]
    if inplace:
        args = "pSrcDst, nValue, pSrcDst, nLength"
    else:
        args = "pSrc, nValue, pDst, nLength"
    if bits:
        return f"npps::constant::{op}<{A}>({args}, nppStreamCtx.hStream)"
    if scale:
        return f"npps::constant::{op}<{A}>({args}, nScaleFactor, nppStreamCtx.hStream)"
    return f"npps::constant::{op}<{A}>({args}, 0, nppStreamCtx.hStream)"

def build_body(rows):
    W = []
    for r in rows:
        if int(r["ctx"]) != 1:
            continue  # plain twins are generated from their _Ctx sibling
        fn = r["function_name"]
        plain = fn[: - 4] if fn.endswith("_Ctx") else fn
        sig = r["signature"]
        params = r["params"]
        # strip the stream-context tail when building the plain signature
        stripped = params
        tail = ", NppStreamContext nppStreamCtx"
        if stripped.endswith(tail):
            stripped = stripped[: - len(tail)]
        plain_names = param_names(stripped)
        call = executor_call(r)
        W.append(f"{sig} {{")
        W.append(f"  return {call};")
        W.append("}")
        W.append("")
        W.append(f"NppStatus {plain}({stripped}) {{")
        W.append("  NppStreamContext nppStreamCtx;")
        W.append("  NppStatus status = nppGetStreamContext(&nppStreamCtx);")
        W.append("  if (status != NPP_NO_ERROR) {")
        W.append("    return status;")
        W.append("  }")
        W.append(f"  return {fn}({', '.join(plain_names)}, nppStreamCtx);")
        W.append("}")
        W.append("")
    return W

def main():
    emit = "--emit" in sys.argv
    rows = list(csv.DictReader(open(CSV)))
    H = [
        "// GENERATED by mpp_scripts/gen_constant_wrappers.py -- DO NOT EDIT.",
        "// Constant scalar arithmetic families (p1.1b): AddC/SubC/SubCRev/MulC/",
        "// DivC/DivCRev/AndC/OrC/XorC/AddProductC/MulC_Low/Normalize.",
        "",
        '#include "npp.h"',
        '#include "npps_constant_executor.h"',
        "",
    ]
    body = build_body(rows)
    text = "\n".join(H + body)
    if emit:
        OUT.write_text(text)
        ctx_count = sum(1 for r in rows if int(r["ctx"]) == 1)
        print("wrote %d _Ctx + adapters -> %s" % (ctx_count, OUT))
    else:
        print(text)
    # validate

if __name__ == "__main__":
    main()
