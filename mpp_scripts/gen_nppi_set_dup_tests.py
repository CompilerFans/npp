#!/usr/bin/env python3
# Differential tests for package p2.1c nppiSet / nppiDup -> suite NppiSetDupDiff.
# Each _Ctx case shares its golden id with a NonCtx twin (NPP_DIFF_HAS_NONCTX)
# that exercises the plain entry point.  Padded rows prove out-of-ROI and AC4
# alpha are preserved.  Usage: python3 gen_nppi_set_dup_tests.py --emit
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "test" / "unit" / "diff" / "test_nppi_set_dup_generated.cpp"

CT = {"8s": "Npp8s", "8u": "Npp8u", "16u": "Npp16u", "16s": "Npp16s", "32u": "Npp32u",
      "32s": "Npp32s", "32f": "Npp32f", "16f": "Npp16f", "16sc": "Npp16sc",
      "32sc": "Npp32sc", "32fc": "Npp32fc"}
VT = {"16f": "Npp32f"}
KIND = {"8u": "U8", "8s": "I8", "16u": "U16", "16s": "I16", "32u": "U32", "32s": "I32",
        "32f": "F32", "16f": "F16", "16sc": "I16Tol", "32sc": "I32Tol", "32fc": "CF32"}
LAY = {"C1": "C1R", "C2": "C2R", "C3": "C3R", "C4": "C4R", "C3C": "C3CR", "C4C": "C4CR",
       "C1M": "C1MR", "C3M": "C3MR", "C4M": "C4MR", "AC4": "AC4R", "AC4M": "AC4MR"}
DUP_LAY = {"C1C3R": (3, 3), "C1C4R": (4, 4), "C1AC4R": (4, 3)}

SET = []
for dt in ("8u", "16u", "16s", "32f", "32s"):
    SET += [(dt, "C2", "vec", 2, 2), (dt, "AC4", "ac", 4, 3), (dt, "C3C", "sc", 3, 0),
            (dt, "C4C", "sc", 4, 0), (dt, "C1M", "ms", 1, 0), (dt, "C3M", "msv", 3, 3),
            (dt, "C4M", "msv", 4, 4), (dt, "AC4M", "mac", 4, 3)]
for lay in ("C1", "C3", "C4"):
    SET.append(("32s", lay, "sc" if lay == "C1" else "vec", int(lay[1]), int(lay[1])))
for d in ("8s", "32u"):
    SET += [(d, "C1", "sc", 1, 0), (d, "C2", "vec", 2, 2), (d, "C3", "vec", 3, 3),
            (d, "C4", "vec", 4, 4), (d, "AC4", "ac", 4, 3)]
for lay, st, cp in (("C1", 1, 0), ("C2", 2, 2), ("C3", 3, 3), ("C4", 4, 4)):
    SET.append(("16f", lay, "sc" if st == 1 else "vec", st, cp))
for d in ("16sc", "32sc", "32fc"):
    SET += [(d, "C1", "sc", 1, 0), (d, "C2", "vec", 2, 2), (d, "C3", "vec", 3, 3),
            (d, "C4", "vec", 4, 4), (d, "AC4", "ac", 4, 3)]

DUP = []
for d in ("16s", "16u", "32f", "32s", "8u"):
    for lay, (st, fl) in DUP_LAY.items():
        DUP.append((d, "%s_%s" % (d, lay), st, fl))

SIZES = [(1, 1), (17, 13), (64, 32)]

def scalar_lit(d):
    return {"8u": "(Npp8u)130", "8s": "(Npp8s)-45", "16u": "(Npp16u)43210",
            "16s": "(Npp16s)-21000", "32u": "(Npp32u)0xF1234567u", "32s": "(Npp32s)-1234567",
            "32f": "1.5f", "16f": "2.5f",
            "16sc": "Npp16sc{(Npp16s)100,(Npp16s)-40}",
            "32sc": "Npp32sc{(Npp32s)123456,(Npp32s)-654321}",
            "32fc": "Npp32fc{1.25f,-2.5f}"}[d]

def elem_lit(d, i):
    if d == "8u": return "(Npp8u)(100 + %d)" % (i * 40)
    if d == "8s": return "(Npp8s)(30 - %d*20)" % i
    if d == "16u": return "(Npp16u)(20000 + %d * 7000)" % i
    if d == "16s": return "(Npp16s)(8000 - %d * 6000)" % i
    if d == "32u": return "(Npp32u)(700000u + %d * 250000u)" % i
    if d == "32s": return "(Npp32s)(-300000 + %d * 200000)" % i
    if d == "32f": return "%sf" % ([1.5, -2.0, 0.75, -1.25][i % 4])
    if d == "16f": return "%sf" % ([1.5, -2.0, 0.75][i % 3])
    if d == "16sc": return "Npp16sc{(Npp16s)(%d),(Npp16s)(%d)}" % (100 + i, -50 - i)
    if d == "32sc": return "Npp32sc{(Npp32s)(%d),(Npp32s)(%d)}" % (10000 + i, -5000 - i)
    if d == "32fc": return "Npp32fc{%sf,%sf}" % ([1.0, -1.0][i % 2], [-0.5, 0.25][i % 2])
    raise KeyError(d)

def value_decl(d, kind, cop):
    v = VT.get(d, CT[d])
    if kind in ("sc", "ms"):
        return "const %s val = %s;" % (v, scalar_lit(d))
    return "const %s nv[%d] = {%s};" % (v, cop, ", ".join(elem_lit(d, i) for i in range(cop)))

def seed_sc(w, h, off):
    return (w * 100 + h) + off

HDR = r'''// Differential tests for the nppiSet / nppiDup families (package p2.c3).
// GENERATED by mpp_scripts/gen_nppi_set_dup_tests.py -- DO NOT EDIT.
//
// Record on the RTX 5090 against NVIDIA NPP 13.4:
//   NPP_RECORD_DIR=... ./diff_tests --gtest_filter='NppiSetDupDiff.*'
// Verify against mcMPP:
//   NPP_VERIFY_DIR=artifacts/5090/npp_records LD_LIBRARY_PATH=build/src \
//     ./build/diff_tests --gtest_filter='NppiSetDupDiff.*'

#include "npp_diff_harness.h"
#include "npp_test_base.h"

#include <cstdint>
#include <memory>
#include <type_traits>
#include <vector>

using namespace npp_diff;
using namespace npp_functional_test;

namespace {

template <typename T> DeviceMemory<T> &arena(std::size_t n) {
  static std::vector<std::unique_ptr<DeviceMemory<T>>> v;
  v.push_back(std::make_unique<DeviceMemory<T>>(n));
  return *v.back();
}

NppStreamContext current_ctx() {
  NppStreamContext c{};
  NppStatus st = nppGetStreamContext(&c);
  EXPECT_EQ(static_cast<int>(st), static_cast<int>(NPP_NO_ERROR));
  return c;
}

// Host fill also covering complex and half destination types.
template <typename T> std::vector<T> dvx(std::size_t n, uint64_t seed) {
  std::vector<T> v(n);
  Rng r(seed);
  for (auto &x : v) {
    if constexpr (std::is_same_v<T, Npp16sc>) { x.re = r.integer<Npp16s>(-3000, 3000); x.im = r.integer<Npp16s>(-3000, 3000); }
    else if constexpr (std::is_same_v<T, Npp32sc>) { x.re = r.integer<Npp32s>(-20000000, 20000000); x.im = r.integer<Npp32s>(-20000000, 20000000); }
    else if constexpr (std::is_same_v<T, Npp32fc>) { x.re = r.unit_float() * 8.f - 4.f; x.im = r.unit_float() * 8.f - 4.f; }
    else if constexpr (std::is_same_v<T, Npp16f>) { x = to_npp16f(static_cast<float>(r.unit_double() * 4.0 - 2.0)); }
    else if constexpr (std::is_floating_point_v<T>) { x = static_cast<T>(r.unit_double() * 8.0 - 4.0); }
    else { x = static_cast<T>(r.integer<uint64_t>(0, ~0ULL)); }
  }
  return v;
}

template <typename D> ValueKind okind() {
  if constexpr (std::is_same_v<D, Npp8u>) return ValueKind::U8;
  else if constexpr (std::is_same_v<D, Npp8s>) return ValueKind::I8;
  else if constexpr (std::is_same_v<D, Npp16u>) return ValueKind::U16;
  else if constexpr (std::is_same_v<D, Npp16s>) return ValueKind::I16;
  else if constexpr (std::is_same_v<D, Npp32u>) return ValueKind::U32;
  else if constexpr (std::is_same_v<D, Npp32s>) return ValueKind::I32;
  else if constexpr (std::is_same_v<D, Npp32f>) return ValueKind::F32;
  else if constexpr (std::is_same_v<D, Npp16f>) return ValueKind::F16;
  else if constexpr (std::is_same_v<D, Npp16sc>) return ValueKind::I16Tol;
  else if constexpr (std::is_same_v<D, Npp32sc>) return ValueKind::I32Tol;
  else return ValueKind::CF32;
}

}  // namespace

class NppiSetDupDiff : public ::testing::Test {
 protected:
  void TearDown() override { (void)cudaDeviceSynchronize(); }
};

'''

def emit_set(dat, w, h, use_ctx):
    d, lay, kind, stride, cop = dat
    s = "%s_%s" % (d, LAY[lay])
    t = CT[d]
    masked = kind in ("ms", "msv", "mac")
    fn = "nppiSet_%s%s" % (s, "_Ctx" if use_ctx else "")
    tail = ", current_ctx()" if use_ctx else ""
    val = "val" if kind in ("sc", "ms") else "nv"
    L = []
    L.append("TEST_F(NppiSetDupDiff, Set_%s_%dx%d_%s) {" % (s, w, h, "Ctx" if use_ctx else "NonCtx"))
    L.append("  " + value_decl(d, kind, cop))
    L.append("  const int w = %d, h = %d, stride = %d, es = (int)sizeof(%s);" % (w, h, stride, t))
    L.append("  const int pixel = stride * es;")
    L.append("  const int step = ((w * pixel + 16 + pixel - 1) / pixel) * pixel;")
    L.append("  const size_t de = (size_t)h * step / es;")
    L.append("  std::vector<%s> pre = dvx<%s>(de, %du);" % (t, t, seed_sc(w, h, 29)))
    L.append("  DeviceMemory<%s>& m = arena<%s>(de); m.copyFromHost(pre);" % (t, t))
    if masked:
        L.append("  const int mstep = w + 3;")
        L.append("  std::vector<Npp8u> mh = dvx<Npp8u>((size_t)h * mstep, %du);" % seed_sc(w, h, 7))
        L.append("  for (auto &z0 : mh) z0 = (Npp8u)(z0 & 1);")
        L.append("  DeviceMemory<Npp8u>& mk = arena<Npp8u>((size_t)h * mstep); mk.copyFromHost(mh);")
    L.append("  NppiSize roi{w, h};")
    L.append("  clear_cuda_error();")
    if masked:
        L.append("  NppStatus st = %s(%s, m.get(), step, roi, mk.get(), mstep%s);" % (fn, val, tail))
    else:
        L.append("  NppStatus st = %s(%s, m.get(), step, roi%s);" % (fn, val, tail))
    L.append('  Case c("nppiSet/%s/%dx%d", "%s");' % (s, w, h, fn))
    L.append("  c.status(st);")
    L.append("  c.device_output<%s>(m.get(), de, ValueKind::%s, 1e-5, 1e-6);" % (t, KIND[d]))
    L.append("  c.finish();")
    L.append("}")
    L.append("")
    return L

def emit_dup(entry, w, h, use_ctx):
    d, s, stride, fill = entry
    t = CT[d]
    fn = "nppiDup_%s%s" % (s, "_Ctx" if use_ctx else "")
    tail = ", current_ctx()" if use_ctx else ""
    L = []
    L.append("TEST_F(NppiSetDupDiff, Dup_%s_%dx%d_%s) {" % (s, w, h, "Ctx" if use_ctx else "NonCtx"))
    L.append("  const int w = %d, h = %d, stride = %d, es = (int)sizeof(%s);" % (w, h, stride, t))
    L.append("  const int sStep = ((w * es + 16 + es - 1) / es) * es;")
    L.append("  const int dStep = ((w * stride * es + 16 + stride * es - 1) / (stride * es)) * (stride * es);")
    L.append("  const size_t se = (size_t)h * sStep / es;")
    L.append("  const size_t de = (size_t)h * dStep / es;")
    L.append("  std::vector<%s> p= dvx<%s>(se, %du);" % (t, t, seed_sc(w, h, 11)))
    L.append("  std::vector<%s> pre = dvx<%s>(de, %du);" % (t, t, seed_sc(w, h, 29)))
    L.append("  DeviceMemory<%s>& s0 = arena<%s>(se); s0.copyFromHost(p);" % (t, t))
    L.append("  DeviceMemory<%s>& m = arena<%s>(de); m.copyFromHost(pre);" % (t, t))
    L.append("  NppiSize roi{w, h};")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = %s(s0.get(), sStep, m.get(), dStep, roi%s);" % (fn, tail))
    L.append('  Case c("idDup/%s/%dx%d", "%s");' % (s, w, h, fn))
    L.append("  c.status(st);")
    L.append("  c.device_output<%s>(m.get(), de, ValueKind::%s, 1e-5, 1e-6);" % (t, KIND[d]))
    L.append("  c.finish();")
    L.append("}")
    L.append("")
    return L
def emit_contract():
    L = []
    L.append("// ===== contract cases (status-only golden) =====")
    L.append("TEST_F(NppiSetDupDiff, Contract_SetNullDst) {")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppiSet_32f_C1R_Ctx(1.0f, nullptr, 8, NppiSize{1, 1}, current_ctx());")
    L.append('  Case c("nppiSet/contract/null", "nppiSet_32f_C1R_Ctx");')
    L.append("  c.status(st); c.finish();")
    L.append("}")
    L.append("")
    L.append("TEST_F(NppiSetDupDiff, Contract_SetEmptyROI) {")
    L.append("  DeviceMemory<Npp8u>& m = arena<Npp8u>(16);")
    L.append("  m.copyFromHost(dvx<Npp8u>(16, 9));")
    L.append("  const Npp8u va2[2] = {1, 2};")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppiSet_8u_C2R_Ctx(va2, m.get(), 8, NppiSize{0, 1}, current_ctx());")
    L.append('  Case c("nppiSet/contract/empty", "nppiSet_8u_C2R_Ctx");')
    L.append("  c.status(st); c.finish();")
    L.append("}")
    L.append("")
    L.append("TEST_F(NppiSetDupDiff, Contract_SetNegativeSize) {")
    L.append("  DeviceMemory<Npp16f>& m = arena<Npp16f>(8);")
    L.append("  m.copyFromHost(dvx<Npp16f>(8, 8));")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppiSet_16f_C1R_Ctx(2.5f, m.get(), 16, NppiSize{-1, 2}, current_ctx());")
    L.append('  Case c("nppiSet/contract/neg", "nppiSet_16f_C1R_Ctx");')
    L.append("  c.status(st); c.finish();")
    L.append("}")
    L.append("")
    L.append("TEST_F(NppiSetDupDiff, Contract_SetShortStep) {")
    L.append("  DeviceMemory<Npp8u>& m = arena<Npp8u>(16);")
    L.append("  m.copyFromHost(dvx<Npp8u>(16, 3));")
    L.append("  const Npp8u va3[3] = {1, 2, 3};")
    L.append("  clear_cuda_error();")
    L.append("  // width=4, AC4 strides 4 -> min dst step 16; give 8 bytes.")
    L.append("  NppStatus st = nppiSet_8u_AC4R_Ctx(va3, m.get(), 8, NppiSize{4, 1}, current_ctx());")
    L.append('  Case c("nppiSet/contract/short", "nppiSet_8u_AC4R_Ctx");')
    L.append("  c.status(st); c.finish();")
    L.append("}")
    L.append("")
    L.append("TEST_F(NppiSetDupDiff, Contract_DupNullSrc) {")
    L.append("  DeviceMemory<Npp8u>& m = arena<Npp8u>(16);")
    L.append("  m.copyFromHost(dvx<Npp8u>(16, 4));")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppiDup_8u_C1C3R_Ctx(nullptr, 16, m.get(), 48, NppiSize{1, 1}, current_ctx());")
    L.append('  Case c("nppiDup/contract/null", "nppiDup_8u_C1C3R_Ctx");')
    L.append("  c.status(st); c.finish();")
    L.append("}")
    L.append("")
    L.append("TEST_F(NppiSetDupDiff, Contract_DupShortStep) {")
    L.append("  DeviceMemory<Npp8u>& s0 = arena<Npp8u>(16); s0.copyFromHost(dvx<Npp8u>(16, 5));")
    L.append("  DeviceMemory<Npp8u>& m = arena<Npp8u>(16); m.copyFromHost(dvx<Npp8u>(16, 6));")
    L.append("  clear_cuda_error();")
    L.append("  // width=4, C1AC4 strides 4 -> min dst step 16; give 8 bytes.")
    L.append("  NppStatus st = nppiDup_8u_C1AC4R_Ctx(s0.get(), 8, m.get(), 8, NppiSize{4, 1}, current_ctx());")
    L.append('  Case c("nppiDup/contract/short", "nppiDup_8u_C1AC4R_Ctx");')
    L.append("  c.status(st); c.finish();")
    L.append("}")
    L.append("")
    return L

def main():
    emit = "--emit" in sys.argv
    body = [HDR]
    for dat in SET:
        for (w, h) in SIZES:
            body += emit_set(dat, w, h, True)
    body.append("#if NPP_DIFF_HAS_NONCTX")
    for dat in SET:
        for (w, h) in SIZES:
            body += emit_set(dat, w, h, False)
    body.append("#endif")
    for entry in DUP:
        for (w, h) in SIZES:
            body += emit_dup(entry, w, h, True)
    body.append("#if NPP_DIFF_HAS_NONCTX")
    for entry in DUP:
        for (w, h) in SIZES:
            body += emit_dup(entry, w, h, False)
    body.append("#endif")
    body += emit_contract()
    text = "\n".join(body) + "\n"
    if emit:
        OUT.write_text(text)
        print("wrote %d test bodies -> %s" % (text.count("TEST_F("), OUT))
    else:
        import sys as _s
        _s.stdout.write(text)

if __name__ == "__main__":
    main()
