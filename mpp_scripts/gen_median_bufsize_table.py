#!/usr/bin/env python3
"""Generate the measured nppiFilterMedian GetBufferSize dispatch table.

The NVIDIA implementation selects a "buffered" median kernel per dtype/channel
layout and mask size; the decision is ROI-independent (verified on the 5090
with ROI 7x7 and 32x32 vs ROI == mask) but not expressible as a simple area
threshold.  The table below is transcribed from the 5090 probe output
(scratch/probe_f9e.cu, section "buf"):

    scratch/remote_out/f9e_buf.out   'P <dtype><layout>' header, then
                                     'h <height> <40 chars>' rows where '#' means
                                     the returned buffer size is > 0.

Usage: python3 mpp_scripts/gen_median_bufsize_table.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROBE = ROOT / "scratch" / "remote_out" / "f9e_buf.out"
OUT = ROOT / "src" / "nppi" / "nppi_filtering_functions" / "nppi_median_bufsize_table.h"

ORDER = [(dt, lay) for dt in ("8u", "16u", "16s", "32f")
         for lay in ("C1", "C3", "C4", "AC4")]
MAX_DIM = 40


def load_probe(path: Path):
    grids = {}
    kind = None
    name = None
    for line in path.read_text().splitlines():
        if line[:2] in ("P ", "B "):
            kind = line[0]
            name = re.sub(r"\s+roi=.*$", "", line[2:].strip())
            grids[(kind, name)] = []
        elif line.startswith("h "):
            if kind != "P":
                continue
            rows = grids[(kind, name)]
            if len(rows) >= MAX_DIM:
                continue
            rows.append(line.split()[2])
    return grids


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="verify the checked-in header matches the probe output")
    args = ap.parse_args()

    grids = load_probe(PROBE)
    lines = [
        "// GENERATED by mpp_scripts/gen_median_bufsize_table.py -- DO NOT EDIT.",
        "// Source: scratch/remote_out/f9e_buf.out (RTX 5090, NVIDIA NPP 13.4).",
        "// Bit (w-1) of row (h-1) is set when nppiFilterMedianGetBufferSize",
        "// returns a non-zero size for mask (w, h); rows are mask heights 1..40.",
        "// Config order: 8u/16u/16s/32f x C1/C3/C4/AC4.",
        "#ifndef NPPI_MEDIAN_BUFSIZE_TABLE_H",
        "#define NPPI_MEDIAN_BUFSIZE_TABLE_H",
        "",
        "#include <cstdint>",
        "",
        "namespace nppi {",
        "namespace filter {",
        "",
        "constexpr int kMedianBufMaxDim = 40;",
        "constexpr int kMedianBufConfigs = 16;",
        "",
        "constexpr std::uint64_t kMedianPlainBufMask[kMedianBufConfigs][kMedianBufMaxDim] = {",
    ]
    for dt, lay in ORDER:
        rows = grids[("P", dt + lay)]
        if len(rows) != MAX_DIM:
            raise SystemExit(f"probe grid for {dt}{lay} has {len(rows)} rows")
        lines.append(f"    {{  // {dt} {lay}")
        for row in rows:
            bits = 0
            for w, ch in enumerate(row):
                if ch == "#":
                    bits |= 1 << w
            lines.append(f"        0x{bits:010x}ull,")
        lines.append("    },")
    lines += [
        "};",
        "",
        "}  // namespace filter",
        "}  // namespace nppi",
        "",
        "#endif  // NPPI_MEDIAN_BUFSIZE_TABLE_H",
        "",
    ]
    text = "\n".join(lines)

    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"out of date: {OUT}")
            return 1
        print(f"up to date: {OUT}")
        return 0

    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
