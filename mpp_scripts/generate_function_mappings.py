#!/usr/bin/env python3
"""
Generate NPP to MPP function mappings.
This creates macro definitions to map all NPP function names to their MPP equivalents.
"""

import re
import os
import glob

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
API_DIR = os.path.join(PROJECT_DIR, 'API')
OUTPUT_FILE = os.path.join(PROJECT_DIR, 'wrapper', 'mpp', 'npp2mpp_functions.h')

def extract_function_names(content):
    """Extract function names starting with npp/nppi/npps."""
    # Strip comments to avoid picking up enum values mentioned in docs.
    content = re.sub(r'/\*.*?\*/', '', content, flags=re.S)
    content = re.sub(r'//.*', '', content)
    pattern = r'\b(npp[ips]?[A-Za-z0-9_]+)\s*\('
    matches = re.findall(pattern, content)
    return sorted(set(matches))

def npp_to_mpp(name):
    """Convert NPP function name to MPP function name."""
    if name.startswith('nppi'):
        return 'mppi' + name[4:]
    elif name.startswith('npps'):
        return 'mpps' + name[4:]
    elif name.startswith('npp'):
        return 'mpp' + name[3:]
    return name

def main():
    """Generate function mappings header."""
    print("Extracting NPP function names...")

    all_functions = set()
    headers = glob.glob(os.path.join(API_DIR, '*.h'))

    for header in headers:
        with open(header, 'r') as f:
            content = f.read()
        functions = extract_function_names(content)
        all_functions.update(functions)

    # Sort and filter
    functions = sorted(all_functions)

    # Exclude core functions (mapped separately in nppcore.h)
    exclude_prefixes = [
        'nppGetLibVersion', 'nppGetGpuNumSMs', 'nppGetMaxThreadsPerBlock',
        'nppGetMaxThreadsPerSM', 'nppGetGpuDeviceProperties', 'nppGetGpuName',
        'nppGetStream', 'nppGetStreamContext', 'nppGetStreamNumSMs',
        'nppGetStreamMaxThreadsPerSM', 'nppSetStream'
    ]

    filtered_functions = []
    for func in functions:
        skip = False
        for prefix in exclude_prefixes:
            if func.startswith(prefix):
                skip = True
                break
        if not skip:
            filtered_functions.append(func)

    print(f"Found {len(filtered_functions)} functions to map")

    # Write header file
    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    with open(OUTPUT_FILE, 'w') as f:
        f.write('''/*
 * Auto-generated NPP to MPP function mappings
 * Generated by generate_function_mappings.py
 */

#ifndef NPP_TO_MPP_FUNCTIONS_H
#define NPP_TO_MPP_FUNCTIONS_H

/* ============================================================================
 * Image Processing Functions (nppi*)
 * ============================================================================ */
''')

        nppi_funcs = [func for func in filtered_functions if func.startswith('nppi')]
        for func in sorted(nppi_funcs):
            mpp_func = npp_to_mpp(func)
            f.write(f'#define {func:<50} {mpp_func}\n')

        f.write('''
/* ============================================================================
 * Signal Processing Functions (npps*)
 * ============================================================================ */
''')

        npps_funcs = [func for func in filtered_functions if func.startswith('npps')]
        for func in sorted(npps_funcs):
            mpp_func = npp_to_mpp(func)
            f.write(f'#define {func:<50} {mpp_func}\n')

        f.write('''
#endif /* NPP_TO_MPP_FUNCTIONS_H */
''')

    print(f"Generated {OUTPUT_FILE}")
    print(f"  - {len(nppi_funcs)} nppi functions")
    print(f"  - {len(npps_funcs)} npps functions")

if __name__ == '__main__':
    main()
