#!/usr/bin/env python3
# One-off generator for the p2.1b nppiCopy variant wrappers (packed AC4R,
# masked MR, channel-conversion C1Cx/CxC1/CxCR). Writes
# src/nppi/nppi_data_exchange_and_initialization/nppi_copy_variants.cpp.

#!/usr/bin/env python3
CT = {
 "8u":"Npp8u","16u":"Npp16u","16s":"Npp16s","32s":"Npp32s","32f":"Npp32f",
 "16f":"Npp16f","8s":"Npp8s","16sc":"Npp16sc","32sc":"Npp32sc","32fc":"Npp32fc",
}
entries=[]
def px(dt,suf,stride): entries.append((dt,suf,stride,stride,False))
def ins(dt,suf,ds): entries.append((dt,suf,1,ds,False))
def ext(dt,suf,ss): entries.append((dt,suf,ss,1,False))
def msk(dt,suf,stride): entries.append((dt,suf,stride,stride,True))

for suf,s in [("16f_C1R",1),("16f_C3R",3),("16f_C4R",4)]: px("16f",suf,s)
for suf,s in [("8s_C1R",1),("8s_C2R",2),("8s_C3R",3),("8s_C4R",4),("8s_AC4R",4)]: px("8s",suf,s)
for dt in ["16sc","32sc","32fc"]:
    for suf,s in [("_C1R",1),("_C2R",2),("_C3R",3),("_C4R",4),("_AC4R",4)]: px(dt,f"{dt}{suf}",s)
for dt in ["8u","16u","16s","32s","32f"]:
    px(dt,f"{dt}_AC4R",4); px(dt,f"{dt}_C3CR",3); px(dt,f"{dt}_C4CR",4)
ins("32f","32f_C1C2R",2)
for dt in ["8u","16u","16s","32s","32f"]:
    ins(dt,f"{dt}_C1C3R",3); ins(dt,f"{dt}_C1C4R",4)
ins("32f","32f_C1C3R",3); ins("32f","32f_C1C4R",4)
ext("32f","32f_C2C1R",2)
for dt in ["8u","16u","16s","32s","32f"]:
    ext(dt,f"{dt}_C3C1R",3); ext(dt,f"{dt}_C4C1R",4)
ext("32f","32f_C3C1R",3); ext("32f","32f_C4C1R",4)
for dt in ["8u","16u","16s","32s","32f"]:
    for suf,s in [("_C1MR",1),("_C3MR",3),("_C4MR",4),("_AC4MR",4)]: msk(dt,f"{dt}{suf}",s)

seen=set(); uniq=[]
for e in entries:
    if e[1] not in seen: seen.add(e[1]); uniq.append(e)

val=[]
val.append("static inline NppStatus validatePlain(const void *pSrc, const void *pDst, int nSrcStep, int nDstStep,")
val.append("                                      NppiSize oSizeROI, int minSrc, int minDst) {")
val.append("  if (oSizeROI.width < 0 || oSizeROI.height < 0) return NPP_SIZE_ERROR;")
val.append("  if (!pSrc || !pDst) return NPP_NULL_POINTER_ERROR;")
val.append("  if (nSrcStep < minSrc || nDstStep < minDst) return NPP_STEP_ERROR;")
val.append("  return NPP_NO_ERROR;")
val.append("}")
val.append("")
val.append("static inline NppStatus validateMasked(const void *pSrc, const void *pDst, int nSrcStep, int nDstStep,")
val.append("                    NppiSize oSizeROI, int minSrc, int minDst, const Npp8u *pMask, int nMaskStep, int minMask) {")
val.append("  NppStatus s = validatePlain(pSrc, pDst, nSrcStep, nDstStep, oSizeROI, minSrc, minDst);")
val.append("  if (s != NPP_NO_ERROR) return s;")
val.append("  if (!pMask || nMaskStep < minMask) return NPP_NULL_POINTER_ERROR;")
val.append("  return NPP_NO_ERROR;")
val.append("}")
val.append("")
val.append("static inline NppStreamContext nppCopyCtx() { NppStreamContext ctx{}; ctx.hStream = nppGetStream(); return ctx; }")
val.append("")

lines=[]
lines.append("// GENERATED by the p2.1b Copy-variant wrapper generator -- DO NOT EDIT by hand.")
lines.append("// Packed AC4R, masked (MR) and channel-conversion nppiCopy variants for package p2.1b.")
lines.append("#include \"npp.h\"")
lines.append("")
lines+=val

lines.append('extern "C" {')
for (dt,suf,ss,ds,mk) in uniq:
    t=CT[dt]; fn=f"nppiCopy_{suf}_Ctx_impl"
    if mk:
        lines.append(f"NppStatus {fn}(const {t} *pSrc, int nSrcStep, {t} *pDst, int nDstStep, NppiSize oSizeROI, const Npp8u *pMask, int nMaskStep, NppStreamContext nppStreamCtx);")
    else:
        lines.append(f"NppStatus {fn}(const {t} *pSrc, int nSrcStep, {t} *pDst, int nDstStep, NppiSize oSizeROI, NppStreamContext nppStreamCtx);")
lines.append("}")
lines.append("")

for (dt,suf,ss,de,mk) in uniq:
    t=CT[dt]; fn=f"nppiCopy_{suf}"; impl=f"nppiCopy_{suf}_Ctx_impl"
    if mk:
        lines.append(f"NppStatus {fn}_Ctx(const {t} *pSrc, int nSrcStep, {t} *pDst, int nDstStep, NppiSize oSizeROI, const Npp8u *pMask, int nMaskStep, NppStreamContext nppStreamCtx) {{")
        lines.append(f"  NppStatus s = validateMasked(pSrc, pDst, nSrcStep, nDstStep, oSizeROI, oSizeROI.width * {ss} * (int)sizeof({t}), oSizeROI.width * {de} * (int)sizeof({t}), pMask, nMaskStep, oSizeROI.width);")
        lines.append("  if (s != NPP_NO_ERROR) return s;")
        lines.append(f"  return {impl}(pSrc, nSrcStep, pDst, nDstStep, oSizeROI, pMask, nMaskStep, nppStreamCtx);")
        lines.append("}")
        lines.append("")
        lines.append(f"NppStatus {fn}(const {t} *pSrc, int nSrcStep, {t} *pDst, int nDstStep, NppiSize oSizeROI, const Npp8u *pMask, int nMaskStep) {{")
        lines.append(f"  return {fn}_Ctx(pSrc, nSrcStep, pDst, nDstStep, oSizeROI, pMask, nMaskStep, nppCopyCtx());")
        lines.append("}")
        lines.append("")
    else:
        lines.append(f"NppStatus {fn}_Ctx(const {t} *pSrc, int nSrcStep, {t} *pDst, int nDstStep, NppiSize oSizeROI, NppStreamContext nppStreamCtx) {{")
        lines.append(f"  NppStatus s = validatePlain(pSrc, pDst, nSrcStep, nDstStep, oSizeROI, oSizeROI.width * {ss} * (int)sizeof({t}), oSizeROI.width * {de} * (int)sizeof({t}));")
        lines.append("  if (s != NPP_NO_ERROR) return s;")
        lines.append(f"  return {impl}(pSrc, nSrcStep, pDst, nDstStep, oSizeROI, nppStreamCtx);")
        lines.append("}")
        lines.append("")
        lines.append(f"NppStatus {fn}(const {t} *pSrc, int nSrcStep, {t} *pDst, int nDstStep, NppiSize oSizeROI) {{")
        lines.append(f"  return {fn}_Ctx(pSrc, nSrcStep, pDst, nDstStep, oSizeROI, nppCopyCtx());")
        lines.append("}")
        lines.append("")

out_path="src/nppi/nppi_data_exchange_and_initialization/nppi_copy_variants.cpp"
open(out_path,"w").write("\n".join(lines))
print("entries",len(uniq))
