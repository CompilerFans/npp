def seedstr(base, tag):
    return str(int(hashlib.sha256((base + "|" + tag).encode()).hexdigest()[:16], 16) & 0x0FFFFFFFFFFFFFFF)

def kind_family(base):
    for f in ("npps10Log10","nppsLShiftC","nppsRShiftC","nppsMul_Low","nppsSumLnGetBufferSize",
              "nppsCauchyDD2","nppsCauchyD","nppsCauchy","nppsSqrt","nppsSqr","nppsExp","nppsLn",
              "nppsAbs","nppsArctan","nppsCubrt","nppsAnd","nppsOr","nppsXor","nppsNot","nppsSumLn"):
        if base.startswith(f):
            return f
    return "nppsUnk"

def vline(dtype, name, n, seed, pos=False):
    ctor = {"Npp16sc":"make_16sc","Npp32sc":"make_32sc","Npp32fc":"make_32fc","Npp64fc":"make_64fc"}
    if dtype in ctor:
        return f"std::vector<{CT[dtype]}> {name} = {ctor[dtype]}(n,{seed});"
    fn = "make_pos" if pos else "make_vec"
    return f"std::vector<{CT[dtype]}> {name} = {fn}<{CT[dtype]}>(n,{seed});"

def dev(dtype, name, host):
    return f"DeviceMemory<{CT[dtype]}> {name}(n); {name}.copyFromHost({host});"

