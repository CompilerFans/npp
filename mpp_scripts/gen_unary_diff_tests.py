"""Generate representative differential tests for the npps unary / bitwise /
shift / reduction families (p1.1c) into test/unit/diff/test_npps_unary_generated.cpp.

Each curated case emits a _Ctx TEST_F plus a plain-entry TEST_F guarded by
NPP_DIFF_HAS_NONCTX that share one case id, so the 5090 recorded golden is
validated against both MPP entry points.  Integers compare exactly; floats use
rtol=atol=1e-5.  SumLn is a reduction case with a device scratch buffer;
GetBufferSize records a real scalar host output.  Cauchy / Mul_Low get dedicated
cases.  A contract block covers null pointer, nLength==0, negative length and
shift out-of-range.

Usage: python3 mpp_scripts/gen_unary_diff_tests.py --emit
"""
