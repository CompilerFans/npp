#!/usr/bin/env python3
"""Generate differential tests for the npps initialization families
(p1.2a) into test/unit/diff/test_npps_initialization_generated.cpp.

Each dtype x length {0,1,17,1024} emits a _Ctx TEST_F plus a plain-entry TEST_F
guarded by NPP_DIFF_HAS_NONCTX that share one case id, so the 5090 recorded
golden is validated against both MPP entry points.  Set additionally covers the
0 / max boundary values.

Usage: python3 mpp_scripts/gen_initialization_diff_tests.py --emit
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "test" / "unit" / "diff" / "test_npps_initialization_generated.cpp"

# dtype -> (C type, ValueKind, count multiplier, is_float, host-vector helper)
D = {
    "8u":  ("uint8_t",   "U8",  1, False, "make_vec"),
    "8s":  ("int8_t",    "I8",  1, False, "make_vec"),
    "16u": ("uint16_t",  "U16", 1, False, "make_vec"),
    "16s": ("int16_t",   "I16", 1, False, "make_vec"),
    "16sc":("Npp16sc",   "I16", 2, False, "v16sc"),
    "32u": ("uint32_t",  "U32", 1, False, "make_vec"),
    "32s": ("int32_t",   "I32", 1, False, "make_vec"),
    "32sc":("Npp32sc",   "I32", 2, False, "v32"),
    "32f": ("float",     "F32", 1, True,  "make_vec"),
    "32fc":("Npp32fc",   "CF32",1, True,  "vfc"),
    "64f": ("double",    "F64", 1, True,  "make_vec"),
    "64fc":("Npp64fc",   "CF64",1, True,  "vfc64"),
    "64s": ("long long", "I64", 1, False, "make_vec"),
    "64sc":("Npp64sc",   "I64", 2, False, "v64sc"),
}

LENGTHS = (0, 1, 17, 1024)


def seedstr(base, tag):
    return str(int(hashlib.sha256((base + "|" + tag).encode()).hexdigest()[:16], 16) & 0x0FFFFFFFFFFFFFFF)


def host_var(dtype, name, n, seed):
    dm = D[dtype]
    if dm[4] == "make_vec":
        return f"std::vector<{dm[0]}> {name} = make_vec<{dm[0]}>(n, {seed});"
    return f"std::vector<{dm[0]}> {name} = {dm[4]}(n, {seed});"


def alloc(dtype, name, n):
    return f"DeviceMemory<{D[dtype][0]}> {name}(n > 0 ? n : 1);"


def value_decl(dtype, value_kind):
    """value_kind in {'normal','zero','max'}."""
    ct = D[dtype][0]
    if dtype == "8s":
        v = 7 if value_kind == "normal" else (0 if value_kind == "zero" else 127)
        return f"{ct} nv = {v};"
    if dtype == "16s":
        v = 9 if value_kind == "normal" else (0 if value_kind == "zero" else 32767)
        return f"{ct} nv = {v};"
    if dtype == "16u":
        v = 11 if value_kind == "normal" else (0 if value_kind == "zero" else 65535)
        return f"{ct} nv = {v};"
    if dtype == "32s":
        v = 13 if value_kind == "normal" else (0 if value_kind == "zero" else 2147483647)
        return f"{ct} nv = {v};"
    if dtype == "32u":
        v = "0x12345678u" if value_kind == "normal" else ("0u" if value_kind == "zero" else "0xFFFFFFFFu")
        return f"{ct} nv = {v};"
    if dtype == "64f":
        v = "0.5" if value_kind == "normal" else ("0.0" if value_kind == "zero" else "1.0e300")
        return f"{ct} nv = {v};"
    if dtype == "64s":
        v = "1234567" if value_kind == "normal" else ("0" if value_kind == "zero" else "9223372036854775807LL")
        return f"{ct} nv = {v};"
    if dtype == "16sc":
        r, i = (3, 2) if value_kind == "normal" else ((0, 0) if value_kind == "zero" else (32767, 32767))
        return f"{ct} nv; nv.re={r}; nv.im={i};"
    if dtype == "32sc":
        r, i = (4, 2) if value_kind == "normal" else ((0, 0) if value_kind == "zero" else (2147483647, 2147483647))
        return f"{ct} nv; nv.re={r}; nv.im={i};"
    if dtype == "64sc":
        r, i = (5, 3) if value_kind == "normal" else ((0, 0) if value_kind == "zero" else ("9223372036854775807LL", "9223372036854775807LL"))
        return f"{ct} nv; nv.re={r}; nv.im={i};"
    if dtype == "32fc":
        r, i = ("1.5f", "0.5f") if value_kind == "normal" else (("0.0f", "0.0f") if value_kind == "zero" else ("3.0e38f", "3.0e38f"))
        return f"{ct} nv; nv.re={r}; nv.im={i};"
    if dtype == "64fc":
        r, i = ("1.0", "2.0") if value_kind == "normal" else (("0.0", "0.0") if value_kind == "zero" else ("1.0e300", "1.0e300"))
        return f"{ct} nv; nv.re={r}; nv.im={i};"
    raise ValueError(dtype)


def tol_of(dtype):
    return "0, 0" if not D[dtype][3] else "1e-5, 1e-5"


HDR = [
    "// Differential tests for the npps initialization families (Set/Copy/Zero).",
    "// GENERATED by mpp_scripts/gen_initialization_diff_tests.py -- DO NOT EDIT.",
    "// Each dtype x length {0,1,17,1024} pairs a _Ctx case with its plain entry",
    "// point sharing one case id, so the 5090 recorded golden is validated against",
    "// both MPP entry points.",
    "",
    '#include "npp_diff_harness.h"',
    '#include "npp_test_base.h"',
    "#include <cmath>",
    "#include <cstdint>",
    "#include <vector>",
    "",
    "using namespace npp_diff;",
    "using namespace npp_functional_test;",
    "",
    "namespace {",
    "",
    "NppStreamContext current_context() {",
    "  NppStreamContext ctx{};",
    "  NppStatus st = nppGetStreamContext(&ctx);",
    "  EXPECT_EQ((int)st, (int)NPP_NO_ERROR) << \"nppGetStreamContext failed\";",
    "  return ctx;",
    "}",
    "",
    "void out2(Case &c, const void *dst, size_t count, ValueKind kind, double rtol = 1e-5, double atol = 1e-5) {",
    "  if (count > 0 && dst != nullptr) c.device_output(static_cast<const Npp8u *>(dst), count, kind, rtol, atol);",
    "}",
    "",
    "template <typename T> std::vector<T> make_vec(size_t n, uint64_t s) {",
    "  std::vector<T> v(n); Rng r(s);",
    "  for (auto &x : v) {",
    "    if constexpr (std::is_same_v<T, float> || std::is_same_v<T, double>) x = static_cast<T>(r.unit_double() * 8.0 - 4.0);",
    "    else x = static_cast<T>(r.integer<uint64_t>(0, ~0ULL));",
    "  }",
    "  return v;",
    "}",
    "std::vector<Npp16sc> v16sc(size_t n, uint64_t s) { std::vector<Npp16sc> v(n); Rng r(s); for (auto &x : v) { x.re = r.integer<Npp16s>(-3000, 3000); x.im = r.integer<Npp16s>(-3000, 3000); } return v; }",
    "std::vector<Npp32sc> v32(size_t n, uint64_t s) { std::vector<Npp32sc> v(n); Rng r(s); for (auto &x : v) { x.re = r.integer<Npp32s>(-20000, 20000); x.im = r.integer<Npp32s>(-20000, 20000); } return v; }",
    "std::vector<Npp64sc> v64sc(size_t n, uint64_t s) { std::vector<Npp64sc> v(n); Rng r(s); for (auto &x : v) { x.re = r.integer<long long>(-2000000, 2000000); x.im = r.integer<long long>(-2000000, 2000000); } return v; }",
    "std::vector<Npp32fc> vfc(size_t n, uint64_t s) { std::vector<Npp32fc> v(n); Rng r(s); for (auto &x : v) { x.re = r.unit_float() * 8.f - 4.f; x.im = r.unit_float() * 8.f - 4.f; } return v; }",
    "std::vector<Npp64fc> vfc64(size_t n, uint64_t s) { std::vector<Npp64fc> v(n); Rng r(s); for (auto &x : v) { x.re = r.unit_double() * 8.0 - 4.0; x.im = r.unit_double() * 8.0 - 4.0; } return v; }",
    "",
    "void finish_case(const char *id, const char *fn, NppStatus st, const void *dst, size_t count,",
    "                 ValueKind kind, double rtol = 1e-5, double atol = 1e-5) {",
    "  Case c(id, fn);",
    "  c.status(st);",
    "  out2(c, dst, count, kind, rtol, atol);",
    "  c.finish();",
    "}",
    "",
]


def emit_copy(dtype, n_flavor, n, seed):
    """n_flavor is the case tag portion of id ('0','1','17','1024')."""
    dm = D[dtype]
    count = dm[2] * n
    tol = tol_of(dtype)
    id_ = f"nppsInit/nppsCopy/{dtype}/{n_flavor}"
    L = [f"// ===== nppsCopy_{dtype} length {n} ====="]
    copy_line = "da.copyFromHost(a);" if n > 0 else ""
    L.append(f"TEST_F(NppsInitialization, Copy_{dtype}_{n_flavor}_Ctx) {{")
    L.append(f"  const NppSignalLength n = {n};")
    L.append("  " + host_var(dtype, "a", n, seedstr(f"nppsCopy_{dtype}", "a")))
    L.append(f"  DeviceMemory<{dm[0]}> da(n > 0 ? n : 1); {copy_line}")
    L.append(f"  DeviceMemory<{dm[0]}> dc(n > 0 ? n : 1);")
    L.append("  clear_cuda_error();")
    L.append(f"  NppStatus st = nppsCopy_{dtype}_Ctx(da.get(), dc.get(), n, current_context());")
    L.append(f'  finish_case("{id_}", "nppsCopy_{dtype}_Ctx", st, dc.get(), {count}, ValueKind::{dm[1]}, {tol});')
    L.append("}")
    L.append("#if NPP_DIFF_HAS_NONCTX")
    L.append(f"TEST_F(NppsInitialization, Copy_{dtype}_{n_flavor}_NonCtx) {{")
    L.append(f"  const NppSignalLength n = {n};")
    L.append("  " + host_var(dtype, "a", n, seedstr(f"nppsCopy_{dtype}", "a")))
    L.append(f"  DeviceMemory<{dm[0]}> da(n > 0 ? n : 1); {copy_line}")
    L.append(f"  DeviceMemory<{dm[0]}> dc(n > 0 ? n : 1);")
    L.append("  clear_cuda_error();")
    L.append(f"  NppStatus st = nppsCopy_{dtype}(da.get(), dc.get(), n);")
    L.append(f'  finish_case("{id_}", "nppsCopy_{dtype}", st, dc.get(), {count}, ValueKind::{dm[1]}, {tol});')
    L.append("}")
    L.append("#endif")
    L.append("")
    return L


def emit_set(dtype, n_flavor, n, seed, value_kind):
    dm = D[dtype]
    count = dm[2] * n
    tol = tol_of(dtype)
    tag = f"{n_flavor}/{value_kind}"
    name_tag = f"{n_flavor}_{value_kind}"
    L = []
    # Main data cases use the "normal" value; every dtype also gets a 0 / max case at n=17.
    for flavour, func, trailer in (("Ctx", f"nppsSet_{dtype}_Ctx", "current_context()"),
                                   ("NonCtx", f"nppsSet_{dtype}", "")):
        L.append(f"TEST_F(NppsInitialization, Set_{dtype}_{name_tag}_{flavour}) {{")
        L.append(f"  const NppSignalLength n = {n};")
        L.append("  " + value_decl(dtype, value_kind))
        L.append(f"  DeviceMemory<{dm[0]}> dc(n > 0 ? n : 1);")
        L.append("  clear_cuda_error();")
        if trailer:
            L.append(f"  NppStatus st = {func}(nv, dc.get(), n, {trailer});")
        else:
            L.append(f"  NppStatus st = {func}(nv, dc.get(), n);")
        L.append(f'  finish_case("nppsInit/nppsSet/{dtype}/{tag}", "{func}", st, dc.get(), {count}, ValueKind::{dm[1]}, {tol});')
        L.append("}")
        L.append("#if NPP_DIFF_HAS_NONCTX" if flavour == "Ctx" else "#endif")
        L.append("")
    return L


def emit_zero(dtype, n_flavor, n, seed):
    dm = D[dtype]
    count = dm[2] * n
    tol = tol_of(dtype)
    id_ = f"nppsInit/nppsZero/{dtype}/{n_flavor}"
    L = [f"// ===== nppsZero_{dtype} length {n} ====="]
    copy_line = "da.copyFromHost(a);" if n > 0 else ""
    L.append(f"TEST_F(NppsInitialization, Zero_{dtype}_{n_flavor}_Ctx) {{")
    L.append(f"  const NppSignalLength n = {n};")
    L.append("  " + host_var(dtype, "a", n, seedstr(f"nppsZero_{dtype}", "a")))
    L.append(f"  DeviceMemory<{dm[0]}> da(n > 0 ? n : 1); {copy_line}")
    L.append("  clear_cuda_error();")
    L.append(f"  NppStatus st = nppsZero_{dtype}_Ctx(da.get(), n, current_context());")
    L.append(f'  finish_case("{id_}", "nppsZero_{dtype}_Ctx", st, da.get(), {count}, ValueKind::{dm[1]}, {tol});')
    L.append("}")
    L.append("#if NPP_DIFF_HAS_NONCTX")
    L.append(f"TEST_F(NppsInitialization, Zero_{dtype}_{n_flavor}_NonCtx) {{")
    L.append(f"  const NppSignalLength n = {n};")
    L.append("  " + host_var(dtype, "a", n, seedstr(f"nppsZero_{dtype}", "a")))
    L.append(f"  DeviceMemory<{dm[0]}> da(n > 0 ? n : 1); {copy_line}")
    L.append("  clear_cuda_error();")
    L.append(f"  NppStatus st = nppsZero_{dtype}(da.get(), n);")
