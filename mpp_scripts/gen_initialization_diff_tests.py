def emit_contract():
    L = ["// ===== contract cases ====="]
    # Null destination for copy - differential golden (record on 5090).
    id_null = "nppsInit/contract/copy_null"
    L.append(f"TEST_F(NppsInitialization, ContractCopyNull_Ctx) {{")
    L.append("  const NppSignalLength n = 8;")
    L.append('  std::vector<float> a = make_vec<float>(n, 77);')
    L.append("  DeviceMemory<float> da(n); da.copyFromHost(a);")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppsCopy_32f_Ctx(da.get(), nullptr, n, current_context());")
    L.append(f'  finish_case("{id_null}", "nppsCopy_32f_Ctx", st, nullptr, 0, ValueKind::F32, 0, 0);')
    L.append("}")
    L.append("#if NPP_DIFF_HAS_NONCTX")
    L.append("TEST_F(NppsInitialization, ContractCopyNull_NonCtx) {")
    L.append("  const NppSignalLength n = 8;")
    L.append('  std::vector<float> a = make_vec<float>(n, 77);')
    L.append("  DeviceMemory<float> da(n); da.copyFromHost(a);")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppsCopy_32f(da.get(), nullptr, n);")
    L.append(f'  finish_case("{id_null}", "nppsCopy_32f", st, nullptr, 0, ValueKind::F32, 0, 0);')
    L.append("}")
    L.append("#endif")
    L.append("")
    # Null source for copy.
    id_src = "nppsInit/contract/copy_srcnull"
    L.append("TEST_F(NppsInitialization, ContractCopySrcNull_Ctx) {")
    L.append("  const NppSignalLength n = 8;")
    L.append("  DeviceMemory<int16_t> dc(n);")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppsCopy_16s_Ctx(nullptr, dc.get(), n, current_context());")
    L.append(f'  finish_case("{id_src}", "nppsCopy_16s_Ctx", st, nullptr, 0, ValueKind::I16, 0, 0);')
    L.append("}")
    L.append("#if NPP_DIFF_HAS_NONCTX")
    L.append("TEST_F(NppsInitialization, ContractCopySrcNull_NonCtx) {")
    L.append("  const NppSignalLength n = 8;")
    L.append("  DeviceMemory<int16_t> dc(n);")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppsCopy_16s(nullptr, dc.get(), n);")
    L.append(f'  finish_case("{id_src}", "nppsCopy_16s", st, nullptr, 0, ValueKind::I16, 0, 0);')
    L.append("}")
    L.append("#endif")
    L.append("")
    # Negative length: not representable on the size_t reference, so it is an
    # MPP-only contract check (skipped in record/verify modes).
    L.append("TEST_F(NppsInitialization, ContractSetNegativeLen) {")
    L.append("  if (recording() || verifying()) GTEST_SKIP() << \"negative length is MPP-only\";")
    L.append("  const int n = -4;")
    L.append("  Npp16s nv = 3;")
    L.append("  DeviceMemory<int16_t> dc(8);")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppsSet_16s_Ctx(nv, dc.get(), n, current_context());")
    L.append("  EXPECT_EQ(static_cast<int>(st), static_cast<int>(NPP_SIZE_ERROR));")
    L.append("}")
    L.append("")
    L.append("TEST_F(NppsInitialization, ContractCopyNegativeLen) {")
    L.append("  if (recording() || verifying()) GTEST_SKIP() << \"negative length is MPP-only\";")
    L.append("  const int n = -4;")
    L.append("  std::vector<int16_t> a = make_vec<int16_t>(8, 88);")
    L.append("  DeviceMemory<int16_t> da(8); da.copyFromHost(a);")
    L.append("  DeviceMemory<int16_t> dc(8);")
    L.append("  clear_cuda_error();")
    L.append("  NppStatus st = nppsCopy_16s_Ctx(da.get(), dc.get(), n, current_context());")
    L.append("  EXPECT_EQ(static_cast<int>(st), static_cast<int>(NPP_SIZE_ERROR));")
    L.append("}")
    L.append("")
    return L


def main():
    emit = "--emit" in sys.argv
    W = list(HDR) + [
        "} // namespace",
        "",
        "class NppsInitialization : public ::testing::Test {",
        "protected:",
        "  void TearDown() override { (void)cudaDeviceSynchronize(); }",
        "};",
        "",
    ]

    COPY_DT = ("8u", "16s", "16sc", "32f", "32fc", "32s", "32sc", "64fc", "64s", "64sc")
    SET_DT = ("16s", "16sc", "16u", "32s", "32sc", "32u", "64f", "64fc", "64s", "64sc", "8s")
    ZERO_DT = ("16s", "16sc", "32fc", "32s", "32sc", "64f", "64fc", "64s", "64sc")

    for dt in COPY_DT:
        W.append(f"// ===== nppsCopy_{dt} =====")
        for n in LENGTHS:
            W += emit_copy(dt, str(n), n, seedstr(f"nppsCopy_{dt}", "n"))

    for dt in SET_DT:
        W.append(f"// ===== nppsSet_{dt} =====")
        for n in LENGTHS:
            W += emit_set(dt, str(n), n, seedstr(f"nppsSet_{dt}", "n"), "normal")
        W += emit_set(dt, "17", 17, seedstr(f"nppsSet_{dt}", "n"), "zero")
        W += emit_set(dt, "17", 17, seedstr(f"nppsSet_{dt}", "n"), "max")

    for dt in ZERO_DT:
        W.append(f"// ===== nppsZero_{dt} =====")
        for n in LENGTHS:
            W += emit_zero(dt, str(n), n, seedstr(f"nppsZero_{dt}", "n"))

    W += emit_contract()

    text = "\n".join(W) + "\n"
    if emit:
        OUT.write_text(text)
        n_cases = text.count("TEST_F(")
        print("wrote %d test bodies -> %s" % (n_cases, OUT))
    else:
        print(text)


if __name__ == "__main__":
    main()
