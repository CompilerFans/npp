#!/usr/bin/env python3
# Generator for package p2.1c nppiDup (duplicate a single-channel image into a
# C3/C4/AC4 destination).  Writes BOTH the executor (nppi_dup.cu) and the public
# wrappers (nppi_dup.cpp) from a single table.
#
#   C1C3R  : STRIDE=3, FILL=3  (every source pixel goes to all 3 channels)
#   C1C4R  : STRIDE=4, FILL=4
#   C1AC4R : STRIDE=4, FILL=3  (alpha channel preserved)
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CU = ROOT / "src/nppi/nppi_data_exchange_and_initialization" / "nppi_dup.cu"
CPP = ROOT / "src/nppi/nppi_data_exchange_and_initialization" / "nppi_dup.cpp"

CT = {"8u": "Npp8u", "16u": "Npp16u", "16s": "Npp16s", "32s": "Npp32s", "32f": "Npp32f"}
LAY = {"C1C3R": (3, 3), "C1C4R": (4, 4), "C1AC4R": (4, 3)}
E = []
for dt in ("16s", "16u", "32f", "32s", "8u"):
    for lay, (st, fl) in LAY.items():
        E.append((dt, f"{dt}_{lay}", st, fl))

KERN = r'''// nppiDup: duplicate a single-channel source into a C3/C4/AC4 destination.
// GENERATED by mpp_scripts/gen_nppi_dup_variants.py -- DO NOT EDIT.
#include "npp.h"
#include <cuda_runtime.h>

// FILL channels of a STRIDE-per-pixel destination receive the single source
// sample.  C1AC4R fills 3 and keeps the 4th (alpha) channel untouched.
template <typename T, int STRIDE, int FILL>
__global__ void kDupC1(const T *pSrc, int nSrcStep, T *pDst, int nDstStep, int width, int height) {
  int x = blockIdx.x * blockDim.x + threadIdx.x;
  int y = blockIdx.y * blockDim.y + threadIdx.y;
  if (x >= width || y >= height) return;
  const T *sr = (const T *)((const char *)pSrc + y * (size_t)nSrcStep);
  T *dr = (T *)((char *)pDst + y * (size_t)nDstStep);
  const T v = sr[x];
#pragma unroll
  for (int c = 0; c < FILL; c++) dr[x * STRIDE + c] = v;
}

template <typename T, int STRIDE, int FILL>
static NppStatus dupRun(const T *pSrc, int nSrcStep, T *pDst, int nDstStep, int width, int height,
                        cudaStream_t stream) {
  if (width == 0 || height == 0) return NPP_NO_ERROR;
  dim3 b(16, 16);
  dim3 g((width + 15) / 16, (height + 15) / 16);
  (void)cudaGetLastError();
  kDupC1<T, STRIDE, FILL><<<g, b, 0, stream>>>(pSrc, nSrcStep, pDst, nDstStep, width, height);
  return cudaGetLastError() == cudaSuccess ? NPP_NO_ERROR : NPP_CUDA_KERNEL_EXECUTION_ERROR;
}

// ---- *_Ctx_impl instantiations (wrappers in nppi_dup.cpp) ----
'''

I = []
for (dt, suf, stride, fill) in E:
    t = CT[dt]
    nm = "nppiDup_%s_Ctx_impl" % suf
    I.append('extern "C" NppStatus %s(const %s *pSrc, int nSrcStep, %s *pDst, int nDstStep, NppiSize oDstSizeROI, NppStreamContext nppStreamCtx) { return dupRun<%s, %d, %d>(pSrc, nSrcStep, pDst, nDstStep, oDstSizeROI.width, oDstSizeROI.height, nppStreamCtx.hStream); }' % (nm, t, t, t, stride, fill))

CU.write_text(KERN + "\n".join(I) + "\n")

VAL = [
 "static inline NppStatus dupValidate(const void *pSrc, const void *pDst, int nSrcStep, int nDstStep,",
 "                                    NppiSize oSizeROI, int minSrc, int minDst) {",
 "  if (oSizeROI.width < 0 || oSizeROI.height < 0) return NPP_SIZE_ERROR;",
 "  if (!pSrc || !pDst) return NPP_NULL_POINTER_ERROR;",
 "  if (nSrcStep < minSrc || nDstStep < minDst) return NPP_STEP_ERROR;",
 "  return NPP_SUCCESS;",
 "}",
 "",
]
W = ["// GENERATED by mpp_scripts/gen_nppi_dup_variants.py -- DO NOT EDIT.",
     "// nppiDup public wrappers for package p2.1c.",
     '#include "npp.h"', ""]
W += VAL
W += ['extern "C" {']
for (dt, suf, stride, fill) in E:
    t = CT[dt]
    nm = "nppiDup_%s_Ctx_impl" % suf
    W.append("NppStatus %s(const %s *pSrc, int nSrcStep, %s *pDst, int nDstStep, NppiSize oDstSizeROI, NppStreamContext nppStreamCtx);" % (nm, t, t))
W.append("}")
W.append("")

for (dt, suf, stride, fill) in E:
    t = CT[dt]
    fn = "nppiDup_%s" % suf
    impl = "%s_Ctx_impl" % fn
    W.append("NppStatus %s_Ctx(const %s *pSrc, int nSrcStep, %s *pDst, int nDstStep, NppiSize oDstSizeROI, NppStreamContext nppStreamCtx) {" % (fn, t, t))
    W.append("  NppStatus s = dupValidate(pSrc, pDst, nSrcStep, nDstStep, oDstSizeROI, oDstSizeROI.width * (int)sizeof(%s), oDstSizeROI.width * %d * (int)sizeof(%s));" % (t, stride, t))
    W.append("  if (s != NPP_SUCCESS) return s;")
    W.append("  return %s(pSrc, nSrcStep, pDst, nDstStep, oDstSizeROI, nppStreamCtx);" % impl)
    W.append("}")
    W.append("")
    W.append("NppStatus %s(const %s *pSrc, int nSrcStep, %s *pDst, int nDstStep, NppiSize oDstSizeROI) {" % (fn, t, t))
    W.append("  NppStreamContext nppStreamCtx;")
    W.append("  NppStatus status = nppGetStreamContext(&nppStreamCtx);")
    W.append("  if (status != NPP_SUCCESS) return status;")
    W.append("  return %s_Ctx(pSrc, nSrcStep, pDst, nDstStep, oDstSizeROI, nppStreamCtx);" % fn)
    W.append("}")
    W.append("")

CPP.write_text("\n".join(W))
print("dup written:", len(E), "variants -> 30 wrappers")
